// MARK: - 语言模型

enum AppLanguage: String, CaseIterable, Identifiable {
    case system, zh, en, ja, ko
    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .system: return L10n.t("lang.auto")
        case .zh: return "简体中文"
        case .en: return "English"
        case .ja: return "日本語"
        case .ko: return "한국어"
        }
    }

    /// 跟随时解析到具体语言
    static func resolve() -> String {
        let pref = Locale.preferredLanguages.first ?? "en"
        for code in ["zh", "en", "ja", "ko"] where pref.hasPrefix(code) {
            return code
        }
        return "en"
    }
}

/// 轻量本地化：单例 + @Published 支持运行时切换
/// 注意：L10n.t 会被后台采集线程并发调用，code 的读写必须加锁
final class L10n: ObservableObject {
    static let shared = L10n()

    @Published var language: AppLanguage {
        didSet {
            UserDefaults.standard.set(language.rawValue, forKey: "netpulse.language")
            lock.lock()
            code = language == .system ? AppLanguage.resolve() : language.rawValue
            lock.unlock()
        }
    }

    private let lock = NSLock()
    private var code: String

    private var currentCode: String {
        lock.lock()
        defer { lock.unlock() }
        return code
    }

    private init() {
        let raw = UserDefaults.standard.string(forKey: "netpulse.language") ?? AppLanguage.system.rawValue
        let lang = AppLanguage(rawValue: raw) ?? .system
        code = lang == .system ? AppLanguage.resolve() : lang.rawValue
        language = lang   // init 中 didSet 不触发，code 已先行就绪
    }

    static func t(_ key: String) -> String {
        let code = shared.currentCode
        return Self.table[code]?[key] ?? Self.table["en"]?[key] ?? Self.table["zh"]?[key] ?? key
    }

    static func tf(_ key: String, _ args: CVarArg...) -> String {
        String(format: t(key), arguments: args)
    }

